package config

import (
	"fmt"
	"log"
	"strings"

	"github.com/spf13/viper"
)

type Config struct {
	Port      string `mapstructure:"PORT"`
	CoreURL   string `mapstructure:"CORE_URL"`
	NodeToken string `mapstructure:"NODE_TOKEN"`
	SFTPPort  string `mapstructure:"SFTP_PORT"`
	DataPath  string `mapstructure:"DATA_PATH"`
}

var NodeConfig Config

func LoadConfig() {
	viper.SetDefault("PORT", "8081")
	viper.SetDefault("CORE_URL", "http://localhost:8080")
	viper.SetDefault("SFTP_PORT", "2022")
	viper.SetDefault("DATA_PATH", "/var/lib/atlas/data")

	viper.SetConfigName("config")
	viper.SetConfigType("env")
	viper.AddConfigPath(".")
	viper.AutomaticEnv()

	if err := viper.ReadInConfig(); err != nil {
		if _, ok := err.(viper.ConfigFileNotFoundError); !ok {
			log.Printf("Error reading config file: %v", err)
		}
	}

	if err := viper.Unmarshal(&NodeConfig); err != nil {
		log.Fatalf("Unable to decode into struct: %v", err)
	}
}

// ValidateNodeToken refuses to run with a missing, placeholder or short token.
func ValidateNodeToken() error {
	t := strings.TrimSpace(NodeConfig.NodeToken)
	switch strings.ToLower(t) {
	case "", "change-me", "changeme", "paste_your_node_token_here":
		return fmt.Errorf("NODE_TOKEN is not set (or is a placeholder). Create a node in the panel and set its token in NODE_TOKEN")
	}
	if len(t) < 16 {
		return fmt.Errorf("NODE_TOKEN is too short (%d chars); use the token generated by the panel", len(t))
	}
	return nil
}
